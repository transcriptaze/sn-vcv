static inline __attribute__((always_inline)) void sincos_lut(uint32_t phase, float &s, float &c) {
    const uint32_t idx = (phase + (1u << (31 - BITS))) >> (32 - BITS);

    // residual in [-0.5, 0.5) cells, built without an int->float convert:
    // flip the sign bit to make the offset unsigned, drop it into the
    // mantissa of a float in [1,2), then subtract 1.5
    const uint32_t m = (((phase << BITS) ^ 0x80000000u) >> 9) | 0x3f800000u;
    float f;
    std::memcpy(&f, &m, 4);
    const float d = (f - 1.5f) * STEP;

    const SC e = tab[idx];
    s = e.s + e.c * d;
    c = e.c - e.s * d;
}

